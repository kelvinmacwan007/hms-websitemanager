export function websiteClassName(className: string): string {
  const classes = className.split(/\s+/).filter(Boolean);
  const resolved = new Map<string, { priority: number; utility: string }>();
  for (const hook of classes) {
    for (const [property, priority, utility] of styles[hook] ?? []) {
      const previous = resolved.get(property);
      if (!previous || priority > previous.priority) resolved.set(property, { priority, utility });
    }
  }
  const primary = classes.some((hook) =>
    ["brand-button", "header-reserve", "footer-book", "stay-cta-button"].includes(hook),
  );
  const variant = primary
    ? "primary"
    : classes.includes("ghost-button")
      ? "secondary"
      : classes.includes("icon-button")
        ? "icon"
        : classes.includes("image-button")
          ? "image"
          : classes.includes("indicator-button")
            ? "indicator"
            : undefined;
  return [
    ...classes,
    ...Array.from(resolved.values(), ({ utility }) => utility),
    variant ? `site-button ${buttonClasses[variant]}` : "",
  ]
    .filter(Boolean)
    .join(" ");
}
